from typing import Final
PI_1016: Final = 3.14
print("pi: %f" % (PI_1016))
jari_1016 = float(input("Masukkan nilai jari-jari: "))
luas_1016 = PI_1016 * jari_1016 * jari_1016
print("Luas lingkaran dengan jari jari %.2f adalah %.2f" % (jari_1016, luas_1016))